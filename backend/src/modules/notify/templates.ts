export type Lang = keyof typeof copy;

export function tplSubmit(opts: {
  lang: Lang;
  docNo: string;
  partnerName: string;
  submittedAt: string;
  fields: Record<string, any>;
  attachmentNames: string[];
}) {
  const c = copy[opts.lang] || copy.en;
  const rows = Object.entries(opts.fields)
    .map(([k, v]) => `<tr><td style="padding:6px 12px;color:#666">${k}</td><td style="padding:6px 12px">${typeof v === 'string' ? v : JSON.stringify(v)}</td></tr>`)
    .join('');
  const files = opts.attachmentNames.length
    ? `<ul>${opts.attachmentNames.map((f) => `<li>${f}</li>`).join('')}</ul>`
    : '<i>(no files)</i>';
  return {
    subject: c.subject(opts.docNo),
    html: `
      <div style="font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;max-width:640px;margin:0 auto">
        <h2 style="color:#1677ff">${c.title}</h2>
        <table cellpadding="0" cellspacing="0" style="width:100%;border-collapse:collapse">
          <tr><td style="padding:6px 12px;color:#666">${c.docNo}</td><td style="padding:6px 12px"><b>${opts.docNo}</b></td></tr>
          <tr><td style="padding:6px 12px;color:#666">${c.partner}</td><td style="padding:6px 12px">${opts.partnerName}</td></tr>
          <tr><td style="padding:6px 12px;color:#666">${c.submittedAt}</td><td style="padding:6px 12px">${opts.submittedAt}</td></tr>
        </table>
        <h3 style="margin-top:20px">${c.fields}</h3>
        <table cellpadding="0" cellspacing="0" style="width:100%;border:1px solid #eee;border-collapse:collapse">${rows}</table>
        <h3 style="margin-top:20px">${c.attachments}</h3>
        ${files}
        <p style="margin-top:24px;font-size:12px;color:#999">${c.footer}</p>
      </div>`,
  };
}

export function tplReject(opts: { lang: Lang; docNo: string; remark: string }) {
  const c = copy[opts.lang] || copy.en;
  return {
    subject: c.rejectSubject(opts.docNo),
    html: `<div style="font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;max-width:640px;margin:0 auto">
      <h2 style="color:#cf1322">${c.rejectTitle}</h2>
      <p><b>${opts.docNo}</b></p>
      <p>${c.remark}：</p>
      <blockquote style="border-left:3px solid #cf1322;padding:8px 12px;background:#fff1f0">${opts.remark}</blockquote>
      <p style="font-size:12px;color:#999">${c.footer}</p>
    </div>`,
  };
}

export function tplRemind(opts: { lang: Lang; docNo: string }) {
  const c = copy[opts.lang] || copy.en;
  return {
    subject: c.remindSubject(opts.docNo),
    html: `<div style="font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;max-width:640px;margin:0 auto">
      <h2 style="color:#d48806">${c.remindTitle}</h2>
      <p>${opts.docNo}</p>
      <p style="font-size:12px;color:#999">${c.footer}</p>
    </div>`,
  };
}
